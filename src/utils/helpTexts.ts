const normalize = (raw: string): string =>
  raw
    .replace(/\u00a0/g, " ")
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[:*]+$/, '')
    .trim()
    .toUpperCase();

/** Help text for a visible label, or '' when there is none. */
export const getHelpText = (label: string | null | undefined, isFinance: boolean): string => {
  if (!label) return '';
  const key = normalize(label);
  if (!key || key.length > 60) return '';
  const lists = isFinance ? [FINANCE, COMMON] : [REGULAR, COMMON];
  for (const list of lists) {
    if (list[key]) return list[key];
  }
  // "Credit (Cr)", "Debit (Dr)", "Amount (₹)" -> try without the bracket part
  const base = key.replace(/\s*\([^)]*\)\s*$/, '').trim();
  if (base && base !== key) {
    for (const list of lists) {
      if (list[base]) return list[base];
    }
  }
  return '';
};
